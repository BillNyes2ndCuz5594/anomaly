// Regenerates src/lib/catalog.generated.ts from the content JSON.
// The benchmark and item lists are APPEND ONLY: report codes store indexes into them.
// New benchmarks or items are added at the end. Existing entries keep their position.
// Usage: node scripts/gen-catalog.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const content = JSON.parse(readFileSync(new URL('../src/content/anomaly-content.json', import.meta.url), 'utf8'))
const OUT = new URL('../src/lib/catalog.generated.ts', import.meta.url)

let prev = { benchmarks: [], items: [] }
try {
  const src = readFileSync(OUT, 'utf8')
  prev = JSON.parse(src.match(/\/\*DATA\n([\s\S]*?)\nDATA\*\//)[1])
} catch {}

const benchmarks = prev.benchmarks.map((b) => b.id)
const items = prev.items.map((i) => i.id)
for (const it of content.items) {
  if (!benchmarks.includes(it.benchmark)) benchmarks.push(it.benchmark)
  if (!items.includes(it.id)) items.push(it.id)
}
const byId = new Map(content.items.map((i) => [i.id, i]))
const short = (s) => (s.length <= 90 ? s : s.slice(0, 87).replace(/\s+\S*$/, '') + '...')
const data = {
  benchmarks: benchmarks.map((id) => ({ id, label: prev.benchmarks.find((b) => b.id === id)?.label ?? LABELS(id) })),
  items: items.map((id) => {
    const it = byId.get(id)
    const old = prev.items.find((i) => i.id === id)
    return { id, benchmark: it?.benchmark ?? old.benchmark, stem: it ? short(it.stem) : old.stem }
  }),
}

function LABELS(id) {
  const m = {
    'SC.5.L.14.1': 'Human organs and functions',
    'SC.5.L.14.2': 'Plant and animal structures',
    'SC.3.L.15.1': 'Classifying animals',
    'SC.5.N.1.1': 'Scientific investigations',
    'SC.5.N.1.2': 'Experiments and other investigations',
    'SC.5.N.1.4': 'Control groups and variables',
    'SC.5.N.1.6': 'Observation versus opinion',
    'SC.5.N.2.1': 'Science needs evidence',
    'SC.5.E.5.2': 'Inner and outer planets',
    'SC.5.E.5.3': 'Objects in the solar system',
    'SC.5.E.7.1': 'The water cycle',
    'SC.5.E.7.2': 'Ocean and the water cycle',
  }
  return m[id] ?? id
}

const ts = `// GENERATED by scripts/gen-catalog.mjs. Do not edit by hand.
// APPEND ONLY: report codes store indexes into these lists, so existing entries must never move.
// Pure data, no imports. Shared by the game (report code) and Teacher HQ (no three).

/*DATA
${JSON.stringify(data, null, 1)}
DATA*/

export interface CatalogBenchmark {
  id: string
  label: string
}
export interface CatalogItem {
  id: string
  benchmark: string
  /** Short stem for teacher views. */
  stem: string
}

export const CATALOG_BENCHMARKS: readonly CatalogBenchmark[] = ${JSON.stringify(data.benchmarks)}

export const CATALOG_ITEMS: readonly CatalogItem[] = ${JSON.stringify(data.items)}
`
writeFileSync(OUT, ts)
console.log(`catalog: ${data.benchmarks.length} benchmarks, ${data.items.length} items`)
